//5. Convert Kilometers to Miles Write a program that takes the distance in 
// kilometers as input from the user and converts it into miles using the formula:
//  Miles = Kilometers * 0.621371.
public class kmtomiles {
    public static void main(String[] args) {
        int k=4;
        double m=k*0.621371;
        System.out.println("the kilomiter is : "+k);
        System.out.println("the miles is : "+m);
    }
    
}
